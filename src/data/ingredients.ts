const toIngredient = (category: Category, entry: Entry): Ingredient =>
  typeof entry === "string" ?
    { name: entry, category, aliases: [] }
  : { name: entry.name, category, aliases: entry.aliases };

/** Every ingredient, alphabetical by name. */
export const INGREDIENTS: Ingredient[] = GROUPS.flatMap(({ category, items }) =>
  items.map((entry) => toIngredient(category, entry)),
).sort((a, b) =>
  a.name < b.name ? -1
  : a.name > b.name ? 1
  : 0,
);
