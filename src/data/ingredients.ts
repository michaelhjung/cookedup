// src/data/ingredients.ts
//
// The ingredient vocabulary shared by the recipe search dropdown, the
// pantry's add-bar suggestions and "Find recipes with what I have".
//
// Conventions, so the list stays consistent as it grows:
// - Lowercase ASCII, spelled the way a US recipe would name it. Other
//   names for the same thing (UK spellings, brands that are the
//   de-facto name, old typos people still type) go in `aliases`, so
//   they match in search and resolve to the canonical entry.
// - Plural for things you count (apples, shallots, eggs, almonds,
//   clams); singular for cuts and mass nouns (salmon, ground beef,
//   flour, ketchup).
// - Herbs live where their most common form is sold: basil, cilantro
//   and parsley are produce; oregano, thyme and rosemary are spices,
//   with "fresh …" / "dried …" entries for the other form.
// - Categories are the pantry's store-walk categories, so a known item
//   lands in the right aisle without guessing (see guessCategory in
//   src/lib/ingredients.ts). Household and Other are never used here.
//
// Every name and alias must be unique once normalized (see
// normalizeItemName); src/lib/ingredients.test.ts enforces it.

